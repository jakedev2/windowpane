#!/usr/bin/env python3
"""
Generates src/sim/PlayerFields.inc from the Geode bindings for the GD version you build against.

    python tools/gen_player_extra.py <path-to>/bindings/bindings/2.2081/GeometryDash.bro > src/sim/PlayerFields.inc

Why this exists
---------------
GD's own PlayerCheckpoint (what practice-mode checkpoints save) only stores ~40 PlayerObject
fields. Everything else that influences the physics (hold state, jump buffering, slope timers,
dash state, rotation speed, ring/pad bookkeeping, ...) is lost on restore. If those are not
restored, a re-simulation drifts away from the real run - typically in ship / wave / UFO
sections, where the held-button state and velocity bookkeeping decide the next frame.

The generator walks every data member of PlayerObject and emits one WP_F(type, name) line for
each member that is plain simulation state. Visual-only members (sprites, particles, colours,
streaks, animation names) and pointers to objects owned by the player are skipped on purpose:
restoring them would corrupt the scene graph and has no effect on physics.
"""
import re
import sys

if len(sys.argv) != 2:
    sys.exit("usage: gen_player_extra.py GeometryDash.bro")

src = open(sys.argv[1], encoding="utf-8").read().splitlines()

start = next(i for i, l in enumerate(src) if re.match(r"^class PlayerObject\b", l))
end = next(i for i in range(start + 1, len(src)) if src[i].startswith("}"))
body = src[start:end]

field_re = re.compile(r"^\s+([A-Za-z_][\w:<>,\*\s]*?)\s+((?:m_|unk_)\w+);")

SKIP_NAME = re.compile(
    r"(Sprite|sprite|Particle|particle|Streak|streak|Trail|trail|Glow|glow|[Ff]lash|"
    r"[Cc]olor|Animation|animation|Batch|iconRequest|Unused|audioScale|ghostType|"
    r"swapColors|defaultMiniIcon|switchDashFireColor|dashFireFrame|"
    r"playEffects|maybeReducedEffects|practiceDeathEffect|hasCustomGlow|"
    r"m_mainLayer|m_gameLayer|m_parentLayer|m_actionManager|m_isSecondPlayer|"
    r"m_pendingCheckpoint|m_unk958|m_particleSystems|m_collisionLog|m_touchingRings|"
    r"m_robotFire|m_swingFire)"
)
SKIP_TYPE = re.compile(
    r"(CCSprite|CCNode|CCLayer|CCArray|CCDictionary|CCMotionStreak|HardStreak|PlayerFireBoostSprite|"
    r"GJRobotSprite|GJSpiderSprite|GhostTrailEffect|CCSpriteBatchNode|CCParticleSystemQuad|"
    r"GJBaseGameLayer|GJActionManager|CheckpointObject|ccColor3B|ccColor4B|ShipStreak|GhostType|gd::string)"
)
OK_TYPE = re.compile(
    r"^(bool|int|unsigned int|unsigned char|char|short|float|double|uint64_t|int64_t|"
    r"cocos2d::CCPoint|geode::SeedValue\w+|"
    r"(?:GameObject|DashRingObject|SlopeObject)\s*\*|"
    r"gd::(?:unordered_map|unordered_set|map|vector)<.*>)$"
)

out = []
for l in body:
    m = field_re.match(l)
    if not m:
        continue
    typ = re.sub(r"\s+", " ", m.group(1)).strip().replace(" *", "*").replace("*", " *").strip()
    typ = typ.replace("  ", " ")
    name = m.group(2)
    if SKIP_NAME.search(name) or SKIP_TYPE.search(typ):
        continue
    t_norm = typ.replace(" *", "*")
    if not OK_TYPE.match(typ) and not OK_TYPE.match(t_norm):
        # unknown enum-like type: keep only if it looks like a plain enum / struct name
        if "*" in typ or "<" in typ:
            continue
    out.append((typ, name))

print("// GENERATED by tools/gen_player_extra.py from the %s bindings - do not edit by hand." % sys.argv[1].split("/")[-2])
print("// %d PlayerObject members captured / restored by sim::PlayerExtra." % len(out))
for typ, name in out:
    # commas inside template args would break the macro, so wrap the type in parentheses
    print("WP_F((%s), %s)" % (typ, name))
